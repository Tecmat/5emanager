export type Lang = 'it' | 'en';

const KEY = 'dnd5e.lang';

export function getLang(): Lang {
  try {
    return localStorage.getItem(KEY) === 'en' ? 'en' : 'it';
  } catch {
    return 'it';
  }
}

export function storeLang(l: Lang): void {
  try { localStorage.setItem(KEY, l); } catch { /* ignora */ }
}

