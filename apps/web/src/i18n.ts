export function t(lang: Lang, key: string, fallback?: string): string {
  return STR[lang][key] ?? fallback ?? key;
}

/** come t(), ma sostituisce le variabili {nome} nel testo */
export function tf(lang: Lang, key: string, fallback: string, vars: Record<string, string | number>): string {
  let s = STR[lang][key] ?? fallback;
  for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
